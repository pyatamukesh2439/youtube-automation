    fun getEnginesByCategory(category: AiCategory): List<AiEngine> {
        return allAiEngines.filter { it.category == category }
    }

    fun searchEngines(query: String): List<AiEngine> {
        if (query.isBlank()) return allAiEngines
        return allAiEngines.filter {
            it.name.contains(query, ignoreCase = true) ||
            it.description.contains(query, ignoreCase = true) ||
            it.features.any { f -> f.contains(query, ignoreCase = true) } ||
            it.provider.contains(query, ignoreCase = true)
        }
    }
